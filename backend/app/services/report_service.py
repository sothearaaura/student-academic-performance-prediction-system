import os
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

PRIMARY = colors.HexColor("#4F46E5")
LIGHT = colors.HexColor("#EEF2FF")


def _styles():
    styles = getSampleStyleSheet()
    styles.add(
        ParagraphStyle(
            name="ReportTitle", fontSize=20, leading=24, textColor=PRIMARY, spaceAfter=6, fontName="Helvetica-Bold"
        )
    )
    styles.add(
        ParagraphStyle(name="ReportSub", fontSize=10, textColor=colors.grey, spaceAfter=16)
    )
    styles.add(ParagraphStyle(name="SectionHeader", fontSize=13, textColor=PRIMARY, spaceBefore=14, spaceAfter=8, fontName="Helvetica-Bold"))
    return styles


def _kv_table(data, col_widths=(6 * cm, 9 * cm)):
    table = Table(data, colWidths=col_widths)
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (0, -1), LIGHT),
                ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#374151")),
                ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 10),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ]
        )
    )
    return table


def generate_student_report(student, prediction, output_path: str, generated_by: str):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    doc = SimpleDocTemplate(output_path, pagesize=A4, topMargin=2 * cm, bottomMargin=2 * cm)
    styles = _styles()
    story = []

    story.append(Paragraph("Student Academic Performance Report", styles["ReportTitle"]))
    story.append(
        Paragraph(
            f"Generated on {datetime.now().strftime('%B %d, %Y %H:%M')} by {generated_by}",
            styles["ReportSub"],
        )
    )

    story.append(Paragraph("Student Information", styles["SectionHeader"]))
    story.append(
        _kv_table(
            [
                ["Student Code", student.student_code],
                ["Full Name", student.full_name],
                ["Gender", student.gender],
                ["Parental Support", student.parental_support],
                ["Attendance Rate", f"{student.attendance}%"],
                ["Weekly Study Hours", str(student.study_hours)],
                ["Previous Grade", str(student.previous_grade)],
                ["Extracurricular Activities", str(student.extracurricular)],
                ["Online Classes", "Yes" if student.online_classes else "No"],
            ]
        )
    )

    if prediction:
        story.append(Paragraph("Prediction Result", styles["SectionHeader"]))
        story.append(
            _kv_table(
                [
                    ["Predicted Final Grade", f"{prediction.predicted_grade:.2f}"],
                    ["Result", prediction.pass_fail],
                    ["Pass Probability", f"{prediction.pass_probability:.1f}%"],
                    ["Confidence Score", f"{prediction.confidence:.1f}%"],
                    ["Performance Level", prediction.performance_level],
                    ["Prediction Date", prediction.created_at.strftime("%Y-%m-%d %H:%M")],
                ]
            )
        )
    else:
        story.append(Paragraph("No prediction has been made for this student yet.", styles["Normal"]))

    story.append(Spacer(1, 20))
    story.append(
        Paragraph(
            "This report was automatically generated by the Student Academic Performance "
            "Prediction System. Predictions are estimates based on historical data and "
            "should be used alongside, not instead of, professional academic judgement.",
            styles["ReportSub"],
        )
    )

    doc.build(story)
    return output_path


def generate_all_students_report(students_with_predictions, generated_by_name, output_path: str):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    doc = SimpleDocTemplate(output_path, pagesize=A4, topMargin=2 * cm, bottomMargin=2 * cm)
    styles = _styles()
    story = [
        Paragraph("All Students Performance Report", styles["ReportTitle"]),
        Paragraph(
            f"Generated by: {generated_by_name}  |  Generated on {datetime.now().strftime('%B %d, %Y %H:%M')}",
            styles["ReportSub"],
        ),
    ]

    rows = [["Student", "Attendance", "Study Hrs", "Prev Grade", "Predicted", "Result"]]
    for student, prediction in students_with_predictions:
        rows.append(
            [
                student.full_name,
                f"{student.attendance}%",
                str(student.study_hours),
                str(student.previous_grade),
                f"{prediction.predicted_grade:.1f}" if prediction else "-",
                prediction.pass_fail if prediction else "-",
            ]
        )

    table = Table(rows, colWidths=[4 * cm, 2.4 * cm, 2.2 * cm, 2.2 * cm, 2.2 * cm, 2 * cm])
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), PRIMARY),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    story.append(table)
    doc.build(story)
    return output_path


def generate_admin_report(stats: dict, output_path: str):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    doc = SimpleDocTemplate(output_path, pagesize=A4, topMargin=2 * cm, bottomMargin=2 * cm)
    styles = _styles()
    story = [
        Paragraph("System-Wide Administrative Report", styles["ReportTitle"]),
        Paragraph(f"Generated on {datetime.now().strftime('%B %d, %Y %H:%M')}", styles["ReportSub"]),
        Paragraph("System Statistics", styles["SectionHeader"]),
        _kv_table(
            [
                ["Total Students", str(stats.get("total_students", 0))],
                ["Total Predictions", str(stats.get("total_predictions", 0))],
                ["Average Predicted Grade", str(stats.get("average_grade", "-"))],
                ["Best Regression Model", stats.get("best_regression_model", "-")],
                ["Best Classifier", stats.get("best_classifier_model", "-")],
            ]
        ),
    ]
    doc.build(story)
    return output_path
